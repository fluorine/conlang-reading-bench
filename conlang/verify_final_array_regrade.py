"""Verify archived responses and both uniformly regraded chart datasets offline."""
import json
from pathlib import Path

from experiments.build_tier3_site import build as build_tier3
from experiments.build_tier4_site import build as build_tier4


def main():
    for tier, builder in ((3, build_tier3), (4, build_tier4)):
        data = builder()
        expected = (f'// Generated by python -m experiments.build_tier{tier}_site; do not edit scores by hand.\n'
                    f'const tier{tier}Research = ' + json.dumps(data, indent=2) + ';\n')
        if Path(f'docs/tier{tier}-results.js').read_text(encoding='utf-8') != expected:
            raise ValueError(f'Tier {tier} chart data differs from the archived responses')
        print(f'Tier {tier}, final-array regrade:')
        for model in data['models']:
            print(f'  {model["name"]}: conlang {model["scores"]["minimal"]:.2f}%; '
                  f'English {model["scores"]["english"]:.2f}%; '
                  f'original conlang {model["strictScores"]["minimal"]:.2f}%; '
                  f'bare-JSON conlang {model["formatCompliance"]["minimal"]:.2f}%; '
                  f'capped {model["capped"]["minimal"]}')


if __name__ == '__main__':
    main()
