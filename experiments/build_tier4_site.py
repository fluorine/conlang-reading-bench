"""Generate Tier 4 chart data from individually verified response archives."""
import json
from pathlib import Path

from conlang.verify_tier4_dynamic import verify_run


def main():
    configs = [('confirm', 'GPT-6 Luna (low)', 'Luna (low)', '2026-09-22'),
               ('luna-medium', 'GPT-6 Luna (medium)', 'Luna (medium)', '2026-09-22'),
               ('terra-medium', 'GPT-6.1 Terra (medium)', 'Terra (medium)', '2026-10-26')]
    models = []
    for prefix, name, short, date in configs:
        rows = []
        for index in range(4):
            manifest = Path(f'experiments/tier4-zero-{prefix}-{index}.json')
            archive = Path(f'reports/tier4-zero-{prefix}-{index}-responses.json')
            verify_run(archive, manifest)
            rows.extend(json.loads(archive.read_text(encoding='utf-8'))['responses'])
        scores = {}
        for key, mode in (('minimal', 'fresh_conlang'), ('english', 'fresh_english')):
            selected = [row for row in rows if row['mode'] == mode and row['stage'] == 0]
            if len(selected) != 48 or any(len(row['marks']) != 4 for row in selected):
                raise ValueError('plot requires 48 stories and four questions per condition')
            scores[key] = 100 * sum(sum(row['marks']) for row in selected) / 192
        models.append({'name': name, 'shortName': short, 'releaseDate': date, 'scores': scores})
    Path('docs/tier4-results.js').write_text(
        '// Generated by python -m experiments.build_tier4_site; do not edit scores by hand.\n'
        + 'const tier4Research = ' + json.dumps({'models': models}, indent=2) + ';\n', encoding='utf-8')


if __name__ == '__main__':
    main()
