"""Generate Tier 5 chart data from the archived held-out runs."""
import argparse
import json
from pathlib import Path

from conlang.tier5_report import report

MANIFEST = "experiments/tier5-heldout-L4.json"
OUT = Path("docs/tier5-results.js")
HEADER = "// Generated by python -m experiments.build_tier5_site; do not edit scores by hand.\n"
CONFIGS = [
    ("reports/tier5-heldout-haiku-low-L4-responses.json", None,
     "Claude Haiku 5.5 (low)", "Haiku 5.5 (low)", "2026-10-07"),
    ("reports/tier5-heldout-sonnet-low-L4-first8-responses.json", 8,
     "Claude Sonnet 5.5 (low)", "Sonnet 5.5 (low)", "2026-09-28"),
]


def build():
    models = []
    for archive, stories, name, short, date in CONFIGS:
        r = report(MANIFEST, archive, stories)
        if not r["complete"]:
            raise ValueError(f"{archive} is missing {r['missing']} requests")
        models.append(dict(
            name=name, shortName=short, releaseDate=date, stories=r["stories"],
            scores=dict(minimal=r["dcs"], english=r["english"]),
            interval=r["dcs_interval95"], stageCurve=r["stage_curve"],
            rulesToSolveMedian=r["rules_to_solve_median"], retention=r["retention"],
            capped=r["capped"], refused=r["refused"]))
    shared = min(m["stories"] for m in models)
    paired = [dict(shortName=short, minimal=report(MANIFEST, archive, shared)["dcs"])
              for archive, _, _, short, _ in CONFIGS]
    return dict(level="L4", stages=len(models[0]["stageCurve"]), models=models,
                pairedStories=shared, paired=paired)


def render():
    return HEADER + "const tier5Research = " + json.dumps(build(), indent=2) + ";\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="fail if the published data differs from the archives")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        if OUT.read_text(encoding="utf-8") != text:
            raise SystemExit(f"{OUT} differs from the archives; rerun the builder")
        return
    OUT.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
